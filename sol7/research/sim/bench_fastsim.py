"""Task 3/4: fastsim throughput and planning budget.

Workloads (same action traces as bench_engine.py):
  pass   : both PASS
  busy   : results/busy_actions.json (generated by bench_engine.py)
  replay : recorded actions from /private/tmp/109564916.json

Measures full-game (719 steps) time, 1-day (24) and 5-day (120) rollouts from
realistic mid-game states (replay step 240 / 480), clone() cost, and
market-only rollouts. Then computes how many rollouts fit into the per-turn
budget: 0.4 s usable + 60 s / 720 turns overage, with a 2x Kaggle slowdown.

Usage: python bench_fastsim.py [--repeats 5] [--json out.json]
"""
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fastsim  # noqa: E402
import validate_replay  # noqa: E402

RESULTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
BUSY_ACTIONS_PATH = os.path.join(RESULTS_DIR, "busy_actions.json")
N_STEPS = 719
PASS = {"farmer": ["PASS"], "hands": [], "market": []}

USABLE_PER_TURN_S = 0.4          # 1 s actTimeout, assume Kaggle 2x slower -> 0.4 s usable of local-equivalent... see below
OVERAGE_TOTAL_S = 60.0
TURNS = 720
KAGGLE_SLOWDOWN = 2.0


def summarize(times, n_steps):
    best = min(times)
    med = sorted(times)[len(times) // 2]
    return {"runs": times, "best_s": best, "median_s": med, "best_steps_per_s": n_steps / best,
            "median_steps_per_s": n_steps / med, "n_steps": n_steps}


def time_full_game(actions, repeats, forced_shops):
    times = []
    for _ in range(repeats):
        s = fastsim.FastState(forced_shops=forced_shops)
        apply = s.apply
        t0 = time.perf_counter()
        for i in range(N_STEPS):
            apply(actions[i + 1])
        times.append(time.perf_counter() - t0)
        final = [s.farms[0].money, s.farms[1].money]
    return times, final


def state_from_replay(rep, step, forced_shops):
    st = rep["steps"][step]
    o = st[0]["observation"]
    privs = [st[p]["observation"]["private"] for p in range(2)]
    return fastsim.FastState.from_obs(o["farms"], o["market"], o["town"], privs, step, forced_shops=forced_shops)


def time_rollouts(base, actions_by_step, horizon, n_rollouts):
    """Clone `base` and apply `horizon` steps of actions_by_step[step] (or PASS).
    Returns seconds per rollout (including clone)."""
    t0 = time.perf_counter()
    for _ in range(n_rollouts):
        s = base.clone()
        apply = s.apply
        st = s.step
        for k in range(horizon):
            apply(actions_by_step(st + k))
    return (time.perf_counter() - t0) / n_rollouts


def time_clone(base, n):
    t0 = time.perf_counter()
    for _ in range(n):
        base.clone()
    return (time.perf_counter() - t0) / n


def main(argv=None):
    argv = list(argv or [])
    repeats = 5
    out = os.path.join(RESULTS_DIR, "bench_fastsim.json")
    while argv:
        a = argv.pop(0)
        if a == "--repeats":
            repeats = int(argv.pop(0))
        elif a == "--json":
            out = argv.pop(0)
    res = {"n_steps_per_game": N_STEPS, "repeats": repeats, "python": sys.version.split()[0], "workloads": {}}

    rep = validate_replay.load_replay()
    forced = validate_replay.recorded_shops(rep["steps"])
    replay_actions = [None] + [[rep["steps"][i][p]["action"] for p in range(2)] for i in range(1, len(rep["steps"]))]
    with open(BUSY_ACTIONS_PATH) as f:
        busy_actions = json.load(f)["actions"]
    pass_actions = [None] + [[PASS, PASS]] * N_STEPS

    for name, acts, desc in (("pass", pass_actions, "both players PASS"),
                             ("busy", busy_actions, "scripted wheat loop, ~10 units/farm + market orders (see bench_engine.py)"),
                             ("replay", replay_actions, "recorded top-player actions, replay 109564916 (mean 9.4 units/farm)")):
        times, final = time_full_game(acts, repeats, forced)
        w = {"description": desc, "full_game": summarize(times, N_STEPS), "final_money": final}
        res["workloads"][name] = w
        print(f"[fastsim {name}] {w['full_game']['best_steps_per_s']:.0f} steps/s, full game {w['full_game']['best_s']*1000:.1f} ms")

    # --- rollouts from realistic mid-game states
    roll = {}
    for base_step in (240, 480):
        base = state_from_replay(rep, base_step, forced)
        # sanity: replaying recorded actions from this state must stay exact
        chk = base.clone()
        for k in range(120):
            chk.apply(replay_actions[base_step + k + 1])
        assert not validate_replay.compare_step(chk, rep["steps"][base_step + 120]), "mid-game state divergence"
        ra = lambda st: replay_actions[st + 1]  # noqa: E731
        pa = lambda st: [PASS, PASS]  # noqa: E731
        entry = {"clone_us": time_clone(base, 2000) * 1e6,
                 "units_per_farm": [len(base.farms[p].units) for p in range(2)]}
        for horizon, label in ((24, "1day"), (120, "5day")):
            n = 400 if horizon == 24 else 100
            entry[f"{label}_replay_actions_ms"] = time_rollouts(base, ra, horizon, n) * 1e3
            entry[f"{label}_pass_actions_ms"] = time_rollouts(base, pa, horizon, n) * 1e3
        roll[f"from_step_{base_step}"] = entry
        print(f"[rollout @{base_step}] clone {entry['clone_us']:.0f}us; 1day replay {entry['1day_replay_actions_ms']:.2f}ms "
              f"pass {entry['1day_pass_actions_ms']:.2f}ms; 5day replay {entry['5day_replay_actions_ms']:.2f}ms pass {entry['5day_pass_actions_ms']:.2f}ms")
    res["rollouts"] = roll

    # --- market-only lookahead
    base = state_from_replay(rep, 240, forced)
    sell_plan_24 = {0: [("MILK", 6), ("WHEAT", 10)], 8: [("EGG", 8)], 16: [("WOOL", 4), ("STRAWBERRY", 4)]}
    sell_plan_120 = {}
    for d in range(5):
        for h, o in sell_plan_24.items():
            sell_plan_120[d * 24 + h] = o
    mk = {}
    for horizon, plan in ((24, sell_plan_24), (120, sell_plan_120)):
        n = 3000 if horizon == 24 else 600
        t0 = time.perf_counter()
        for _ in range(n):
            fastsim.market_only_rollout(base.minv, base.shops, base.step, horizon, plan, forced)
        per = (time.perf_counter() - t0) / n
        mk[f"{horizon}step"] = {"seconds_per_rollout": per, "rollouts_per_s": 1.0 / per,
                                "units_sold_per_rollout": sum(n_ for o in plan.values() for _, n_ in o),
                                "shops": len(base.shops)}
        print(f"[market-only {horizon} steps] {1/per:.0f} rollouts/s ({per*1e6:.0f} us)")
    # price function alone
    t0 = time.perf_counter()
    for _ in range(20000):
        fastsim.market_price("MILK", 9990)
    mk["market_price_call_us"] = (time.perf_counter() - t0) / 20000 * 1e6
    res["market_only"] = mk

    # --- budget
    per_turn_local = (USABLE_PER_TURN_S + OVERAGE_TOTAL_S / TURNS) / KAGGLE_SLOWDOWN  # local-machine seconds equivalent
    # NOTE: 0.4 s "usable" is already the Kaggle-side figure (1 s * 0.4 safety). We interpret the
    # budget as 0.4 s + 0.0833 s of *Kaggle* time per turn, i.e. local time x2 must fit in it.
    budget = {"kaggle_seconds_per_turn": USABLE_PER_TURN_S + OVERAGE_TOTAL_S / TURNS,
              "usable_per_turn_s": USABLE_PER_TURN_S, "overage_per_turn_s": OVERAGE_TOTAL_S / TURNS,
              "kaggle_slowdown_factor": KAGGLE_SLOWDOWN, "local_seconds_per_turn_equivalent": per_turn_local,
              "rollouts_per_turn": {}}
    r240 = roll["from_step_240"]
    full_replay = res["workloads"]["replay"]["full_game"]["best_s"]
    full_pass = res["workloads"]["pass"]["full_game"]["best_s"]
    items = {
        "1day_realistic": r240["1day_replay_actions_ms"] / 1e3,
        "1day_pass": r240["1day_pass_actions_ms"] / 1e3,
        "5day_realistic": r240["5day_replay_actions_ms"] / 1e3,
        "5day_pass": r240["5day_pass_actions_ms"] / 1e3,
        "full_game_realistic": full_replay,
        "full_game_pass": full_pass,
        "market_only_24step": mk["24step"]["seconds_per_rollout"],
        "market_only_120step": mk["120step"]["seconds_per_rollout"],
    }
    for k, sec in items.items():
        budget["rollouts_per_turn"][k] = {"local_seconds_per_rollout": sec,
                                          "kaggle_seconds_per_rollout": sec * KAGGLE_SLOWDOWN,
                                          "rollouts_per_turn": per_turn_local / sec}
    res["budget"] = budget
    print("[budget] local-equivalent s/turn:", round(per_turn_local, 4))
    for k, v in budget["rollouts_per_turn"].items():
        print(f"   {k:22s} {v['kaggle_seconds_per_rollout']*1e3:9.2f} ms(kaggle)  -> {v['rollouts_per_turn']:10.1f} rollouts/turn")

    with open(out, "w") as f:
        json.dump(res, f, indent=1)
    return res


if __name__ == "__main__":
    main(sys.argv[1:])
